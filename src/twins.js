/** name → the names it is twinned with. */
export function twinIndex (pairs = TWIN_PAIRS) {
  const out = new Map();
  for (const [a, b] of pairs) {
    out.set(a, [...(out.get(a) || []), b]);
    out.set(b, [...(out.get(b) || []), a]);
  }
  return out;
}
