let byCode = null;
function index () {
  if (byCode) return byCode;
  byCode = new Map();
  let cp = 0;
  for (const line of TABLE.trim().split('\n')) {
    if (line.startsWith('@')) { cp = parseInt(line.slice(1), 16); continue; }
    byCode.set(cp, line);
    cp++;
  }
  return byCode;
}

