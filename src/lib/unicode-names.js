export function searchNames (needle, limit) {
  const q = needle.toUpperCase();
  const hits = [];
  for (const [cp, nm] of index()) {
    if (nm.includes(q)) { hits.push({ codePoint: cp, name: nm }); if (hits.length >= limit) break; }
  }
  return hits;
}
