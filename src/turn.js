/* turn.js — §3's four passes, in order, with no DOM anywhere in sight.
 *
 *   Message → [1] Router → [2] Planner → JS: validate plan → [3] Executor loop
 *           → [4] Assembler → UI render with provenance marks
 *
 * Which of those are real in this build, and what stands in where they are not,
 * is stated in `stackReport()` at the bottom and shown in the app's rail. The
 * shape of the pipeline does not change when a real model arrives: pass a
 * `planner` and an `assembler` and the same code takes the other branch. That
 * is §11's requirement that the fallback be "a config flag, not a rewrite". */

import { OUTCOME, ERROR_CODES, CTX_OWNED_FIELDS } from './contracts.js';
import { twinIndex } from './twins.js';
import { engineRows } from './engine.js';
import { validatePlan } from './plan.js';
import { auditInput } from './audit-input.js';
import { runPlan } from './executor.js';
import { rivalFor } from './tiebreak.js';
import { replyFor, REPLY_SOURCES } from './reply.js';
import { alignToCarry } from './carry.js';

/* The message sources a carried answer is honoured for. */
/* Patch's default for runTurn's fallbackOnEmpty — packed as
   tunables.turn.fallback_on_empty, so a Patch update can change it. */
export const FALLBACK_ON_EMPTY = false;

export const CARRY_SOURCES = Object.freeze(['typed', 'person-confirmed']);

export const MODES = Object.freeze({
  NO_SKILL: 'no-skill',
  SINGLE_SKILL: 'single-skill',
  PLANNED: 'planned',
  HAND_WRITTEN: 'hand-written'
});

/**
 * One conversational turn.
 * @param {string} message
 * @param {object} deps
 * @param {Registry} deps.registry
 * @param {object}   deps.router      anything satisfying the router interface
 * @param {object}   deps.ctx
 * @param {Function|null} deps.planner    (message, cards, ctx) => plan JSON
 * @param {Function|null} deps.extractor
 * @param {Function|null} deps.assembler
 * @param {object|null}   deps.prev       the previous turn, for $prev refs
 * @param {object|null}   deps.pending    an unanswered ASK_USER to resume
 * @param {object|null}   deps.plan       a hand-written plan, bypassing 1–2
 * @param {Function|null} deps.onNetworkConfirm  asked before each web request
 * @param {Function|null} deps.onStage   (name, detail) as each pass begins
 * @param {Function|null} deps.tieBreak  asked when the pick has a close twin
 */
export async function runTurn (message, {
  registry, router, ctx, planner = null, extractor = null, assembler = null,
  prev = null, pending = null, plan: given = null, onNetworkConfirm = null,
  trustRouter = false, focus = null, fallbackOnEmpty = FALLBACK_ON_EMPTY,
  verify = null, secondLook = null, groundCheck = false, asksCheck = null,
  onStage = null, tieBreak = null, carry: replyingTo = null, source = 'typed', consent = null,
  /* The planner is handed this one skill's card and no other: the person
     tapped "or dayOfWeek?" under an answer, and the turn is asked again with
     the twin they chose. The turn records it as `chosen`. */
  onlySkill = null
} = {}) {
  /* A carried answer rides only on words the person typed or confirmed. Text
     that arrived some other way — handed over from another chat, say — is
     planned on its own, so nothing a model wrote can reach into a figure. */
  const carry = replyingTo && CARRY_SOURCES.includes(source) ? replyingTo : null;
  const t0 = Date.now();
  /* How long each model stage took, for the plan view to say so. The turn
     already carries its total; the router and planner are the two calls a
     person waits on, and "1.1 s" under Patch's line is worth more than the
     sum at the top. */
  const stages = {};
  /* Report where the turn has got to, as it gets there.
   *
   * The reply is NOT generated by a model — it is rendered from templates once
   * the skill has run — so there is no stream of words to show while a question
   * is being answered. What there is, is a sequence of real steps, some of them
   * slow: a model picking a category, a model writing a plan, a skill running,
   * sometimes a request leaving the machine. Reporting those as they happen is
   * the honest version of a progress indicator; a bar that fills on a timer
   * would be an animation pretending to be information. */
  const stage = (name, detail) => { if (onStage) { try { onStage(name, detail); } catch { /* a display must never break a turn */ } } };
  /* `carry` is the answer this message replies to, and only a Reply sets it.
     When it is there, "$prev" refs read from it; otherwise from the previous
     turn, as they always have. */
  const prevResults = ((carry || prev) && (carry || prev).results) || [];
  /* What the sibling check or the decline second look decided, if either ran. */
  let verified = null;
  /* Set when the asks check vetoed a plan, so the turn can say a plan existed
     and was dropped rather than that nothing was found. */
  let asked = null;

  /* ── resuming an ASK_USER ────────────────────────────────────────────────
     The answer is written into the step that asked, and the plan is re-run
     from the top. Skills are pure (§3.3), so replaying the steps that already
     succeeded costs a millisecond and cannot produce a different result — and
     it keeps the resumed turn a single, inspectable execution rather than a
     stitched-together pair of half-turns. */
  /* ── answering a look-up's question ─────────────────────────────────────
     Send once re-runs the plan with that one step allowed and the query as it
     stood in the box; Don't send closes the turn with nothing sent. */
  if (pending && pending.consent) {
    const plan = clone(pending.plan);
    const asked = pending.consent;
    if (!consent || !consent.send) {
      return {
        message: pending.message, routing: pending.routing, plan, ask: null, answered: null, consentDeclined: true,
        results: [...(pending.results || []), {
          id: asked.step, skill: asked.skill, input: asked.field ? { [asked.field]: asked.query } : {}, ok: false,
          error: { code: ERROR_CODES.NETWORK_OFF, field: null, message: 'You chose not to send it, so nothing left this Mac.' },
          provenance: null, labels: [], ms: 0
        }],
        mode: pending.mode, reply: { source: REPLY_SOURCES.NO_SKILL, segments: [], notes: [] }, ms: Date.now() - t0, stages
      };
    }
    return finish({
      message: pending.message, routing: pending.routing, plan, mode: pending.mode,
      consentAnswer: { step: asked.step, field: asked.field, query: typeof consent.query === 'string' ? consent.query : asked.query }
    });
  }

  if (pending) {
    const plan = clone(pending.plan);
    const step = plan.steps.find(s => s.id === pending.ask.step);
    /* No step to answer means the pending record and the plan disagree, which
       is a bug rather than a user error. Re-running the original plan would
       silently ask the same question again, so say so instead. */
    if (!step) {
      return {
        message: pending.message, routing: pending.routing, plan, results: [], ask: null,
        answered: null, mode: pending.mode, reply: null, ms: Date.now() - t0, stages,
        invalid: [{ message: `the answer had nowhere to go: step ${pending.ask.step} is not in the plan` }]
      };
    }
    step.input = { ...step.input, [pending.ask.field]: answerFor(registry, step, pending.ask.field, message) };
    return finish({
      message: pending.message,
      /* The raw text, not the coerced value: the transcript shows what the
         person typed, and the plan shows what it became. */
      answered: { field: pending.ask.field, step: pending.ask.step, value: message },
      routing: pending.routing,
      plan,
      mode: pending.mode
    });
  }

  /* ── a hand-written plan skips passes 1 and 2 entirely (§9 Phase 0) ────── */
  if (given) {
    return finish({ message, routing: null, plan: given, mode: MODES.HAND_WRITTEN });
  }

  // ── [1] Router ──────────────────────────────────────────────────────────
  /* Awaited, though LexicalRouter returns synchronously — awaiting a plain
     object is a no-op, and a router that consults a model has to be async.
     Without this the interface silently excludes every backend except a lexical
     one, which is the opposite of what §3.1's "swap the backend" promise means. */
  stage('routing');
  const tRoute = Date.now();
  /* A Reply is routed on its own words. The earlier answer reaches the planner
     through its own block; mixed into routing as well, it ranked the skill that
     made the earlier answer first ("add 10% to the monthly payment" → the loan
     again) instead of the operation now being asked for. */
  const routing = await router.route(message, {
    prevMessage: carry ? '' : ((prev && prev.message) || ''),
    prevSkills: carry ? [] : prevResults.map(r => r.skill)
  });
  stages.router = Date.now() - tRoute;

  /* §3: "Low router confidence skips passes 2–3 entirely." Which gate counts as
     "low confidence" depends on whether pass 2 exists.
     
     Without a planner, single-skill mode acts on the top candidate alone, so it
     needs the MARGIN gate: a tie between two neighbours cannot be resolved by
     anything downstream, and guessing one is the failure §3 exists to prevent.
     
     With a planner, a tie is exactly what pass 2 is for. Gating on `actionable`
     there would hand the planner only the questions that did not need it, and
     silently skip it on the ones that did — which is what this code did until
     the planner benchmark showed 14 declines the model resolves correctly on
     its own. So the planner sees anything that cleared t_skill, ties included. */
  /* A Reply carrying an answer is often too short for the router ("split that
     3 ways" has nothing to match), so the planner is shown the router's top
     candidates even when none cleared the floor — it still has to choose. */
  const confident = planner
    ? (routing.forPlanner.length || !carry ? routing.forPlanner : (routing.candidates || []).slice(0, 5))
    : routing.actionable;
  if (!confident.length) {
    return {
      message, routing, plan: null, results: [], ask: null,
      suggestions: routing.suggestions || [],
      /* Declined by the router with no planner to ask: the models could still
         find a skill for it, and the window can offer to wake them. */
      ...(planner ? {} : { routerOnly: true }),
      mode: MODES.NO_SKILL,
      reply: { source: REPLY_SOURCES.NO_SKILL, segments: [], notes: [] },
      ms: Date.now() - t0, stages
    };
  }

  // ── [2] Planner ─────────────────────────────────────────────────────────
  let plan;
  let mode;
  if (planner) {
    /* TRUST A CONFIDENT ROUTER. When the router has an `actionable` pick — top
       candidate over t_skill AND clear of the runner-up by the margin — that is
       the same evidence single-skill mode acts on alone, and it is right far
       more often than a 2B planner choosing among twenty neighbours: measured
       live, the router put convertLength at 0.70 over convertSpeed at 0.27 and
       the planner still chose convertSpeed. So with `trustRouter` the planner is
       handed that one skill and its job becomes what §3.2 actually needs from
       it — copying the arguments out of the sentence. The grammar then cannot
       name anything else, and an empty plan still means "no skill". Ties and
       low-confidence routings are unchanged: the planner keeps the full list,
       which is where it earns its keep. */
    const trusted = trustRouter && routing.actionable && routing.actionable.length ? routing.actionable : null;
    const listed = onlySkill ? [{ name: onlySkill }] : (trusted || confident);
    const cards = listed.map(c => registry.compactCard(c.name)).filter(Boolean);
    /* `routerConfident` tells the planner whether the router believes there is
       a skill here at all. Two signals count, and the second is the one that
       matters: the lexical gate (top over t_skill and clear of the runner-up),
       and the category adapter naming a category at or above its confidence
       bar. Measured on the 302-question holdout and the 50 no-skill messages,
       the lexical gate fires on 88 and 3; the adapter names a category on 280
       and 1. That second pair is the discriminator this pipeline lacked — "is
       there a skill for this?" answered before the planner is asked which. A
       planner in `runway: 'auto'` mode uses it to decide how much room to
       think it gets; see planner.js for why that is the right lever. */
    const categoryNamed = typeof routing.category === 'string' && !['none', 'unavailable'].includes(routing.category);
    /* A Reply to a worked-out answer is a request by construction — the person
       pointed at a figure and asked for something done to it — so it gets the
       room to think that a confident router would have given it. */
    const routerConfident = Boolean(routing.actionable && routing.actionable.length) || categoryNamed || Boolean(carry);
    stage('planning', { candidates: cards.length, category: routing.category || null });
    const tPlan = Date.now();
    /* Asked AT THE SAME TIME as the planner, not after it: the question is
       about the message, not the plan, so there is nothing to wait for. On a
       server with one slot the two still queue — measured at +185 ms a turn —
       so this is cheaper than asking afterwards but is not free. See verify.js. */
    const asking = asksCheck ? asksCheck(message) : null;
    /* The plan is read whole when it is back; its first skill is known a few
       tokens in, and the stage line says so while the arguments are written. */
    plan = await planner({ message, cards, ctx, prev, carry, routerConfident, onSkill: (skill, n) => stage('reaching', { skill, n, category: routing.category || null }) });
    stages.planner = Date.now() - tPlan;
    mode = MODES.PLANNED;

    /* THE ASKS CHECK. A plan for a message that was not asking for anything is
       the leak this pipeline has left: "my morse code is rusty" belongs to
       encoding as far as its words go, and no confidence gate reaches it
       because the adapter is certain and certain about the wrong thing.
       Measured: 12 of 17 remaining leaks stopped, 3 of 308 real questions lost.
       See verify.js for the shots that make it work at all. */
    if (asking) {
      const verdict = await asking;
      stages.asks = verdict.ms;
      if (!verdict.asks) {
        asked = { asks: false, said: verdict.said };
        plan = { steps: [] };
      }
    }

    /* THE SIBLING CHECK. A single-step plan is put to a second, smaller
       question: this skill, or one of its nearest siblings? JS picks the
       siblings; the model only selects; a switch sends the planner back with
       ONE card to write the arguments. See verify.js for the measurements
       that shaped this. */
    if (verify && plan && Array.isArray(plan.steps) && plan.steps.length === 1) {
      const v = await verify({ message, skill: plan.steps[0].skill, routing });
      if (v) {
        verified = { ...v, lexicalTop: routing.candidates && routing.candidates[0] ? routing.candidates[0].name : null };
        if (v.chosen !== v.draft) {
          const card = registry.compactCard(v.chosen);
          const again = card ? await planner({ message, cards: [card], ctx, prev, carry, routerConfident }) : null;
          if (again && Array.isArray(again.steps) && again.steps.length && again.steps.every(st => st.skill === v.chosen)) {
            plan = again;
          } else {
            verified = { ...v, chosen: v.draft, replanFailed: true };
          }
        }
      }
    }

    /* THE GROUND CHECK. A plan that takes nothing from the message, on a turn
       where the adapter was not fully certain of the neighbourhood, is a plan
       about nothing.

       Measured on the twenty leaks: seven carry no value traceable to the
       message at all — "binary thinking is what got us into this" becomes
       binaryDecode with an empty input, the extractor fills the field from the
       sentence, and the skill answers about nothing. The same shape appears on
       real questions ("tidy this json" is also an empty input), so absence
       alone cannot decide it. What separates the two in the probe is the
       adapter's own confidence: the real ones sit at 1.00 and the leaks at
       0.52–0.99.

       Suppressing the plan rather than dropping a field is deliberate. An ask
       is still an answer to a message that wanted none — "Which text should I
       hash?" to "he made a hash of the presentation" is the wrong reply, and
       the bench counts it as one.

       MEASURED, AND THAT IS WHY IT IS OFF. On the 308 + 100 bench it stopped
       six leaks (20 → 14) and cost nine correct answers (292 → 283), against a
       rule written before the run of "fewer than two". The nine are all the
       same shape and it is the shape the empty-input shot was added to rescue:
       "squash this text down", "what stands out in this document", "lift the
       fenced snippets out of this doc" — a person naming the thing to work on
       without having pasted it yet. The adapter is not fully certain on those
       either, so the confidence signal that looked separable in a 40-turn probe
       does not hold at 308.

       THAT PARAGRAPH USED TO SAY THE LEAK WAS UPSTREAM — that the adapter names
       a category at 0.9-1.00 for "he made a hash of the presentation", and that
       targeted negatives in the category set were the lever. Both halves were
       measured on 2026-09-10 and both are wrong.

       The shipped adapter REFUSES that sentence, at 1.00. Asked one at a time,
       it refuses 12 of the 21 leaking messages and 91 of the 100 in the
       no-skill set. The leak is not upstream; it is in the FALLBACK, where the
       adapter's refusal is overruled by word matching, which always finds
       something to hand the planner. `fallbackFloor` in category-router.js is
       the fix that followed: 21 leaks to 17, for one answer.

       The negatives were built and tried anyway, because the comment said so.
       512 generated, filtered to the 226 the adapter actually gets wrong,
       trained as category v4 at 16.0% refusals. Result: 269/308 correct
       against v3's 291, for one leak. It refuses 74 of 308 real questions
       where v3 refuses 25 — it did not learn that an idiom is not a request,
       it learned to refuse. That is what v2 did at 16.1%, and the set is kept
       in model/negatives with the numbers so the third attempt starts here. */
    if (groundCheck && plan && Array.isArray(plan.steps) && plan.steps.length === 1 &&
        typeof routing.confidence === 'number' && routing.confidence < 1) {
      const skill = registry.skill(plan.steps[0].skill);
      if (skill) {
        const audit = auditInput(plan.steps[0].input || {}, { message, skill });
        const props = (skill.inputSchema && skill.inputSchema.properties) || {};
        const grounded = Object.entries(audit.input).some(([field, value]) => {
          const prop = props[field] || {};
          if (CTX_OWNED_FIELDS.includes(field)) return false;
          if (Array.isArray(prop.enum)) return false;
          if (prop.default !== undefined && JSON.stringify(prop.default) === JSON.stringify(value)) return false;
          return true;
        });
        if (!grounded) plan = { steps: [] };
      }
    }

    /* §3.2: the planner may legitimately return an empty plan — "no skill
       needed" — even when the router offered candidates. */
    /* One more question, when the pick has a twin.
     *
     * The planner decides WHICH skill and WHAT arguments in a single pass over
     * as many as twenty candidates. Its remaining mistakes are mostly not wild
     * — they are a near-twin of the right skill, in the right category, where
     * the distinction is one detail in the message. Asked on its own, with two
     * cards instead of twenty, that is a much easier question.
     *
     * It can only ever swap the chosen skill for a same-category rival the
     * router already offered, and only when that rival scored close to the pick
     * or above it. Everything else about the plan — the arguments, the steps —
     * is left alone. */
    if (tieBreak && plan && plan.steps && plan.steps.length === 1) {
      const chosen = plan.steps[0].skill;
      const rival = rivalFor(routing, registry, chosen);
      if (rival) {
        stage('deciding', { between: [chosen, rival] });
        const winner = await tieBreak({ message, a: chosen, b: rival });
        /* A tie-break that cannot answer leaves the planner's choice standing.
           Swapping the skill keeps the arguments: they were extracted from the
           same message, and the executor validates them against the new skill's
           schema anyway — a mismatch becomes an honest ASK_USER rather than a
           wrong answer. */
        if (winner && winner !== chosen) plan.steps[0].skill = winner;
      }
    }

    if (!plan || !Array.isArray(plan.steps) || !plan.steps.length) {
      /* NOT A REQUEST STAYS DECLINED. Every rescue below exists to recover a
         real question the planner gave up on. A message the asks check found
         was not asking for anything is not one of those, and rescuing it undid
         the check: measured at 3a461cd, the second look's 33 rescues answered
         18 no-skill messages ("my morse code is rusty" → morseEncode, "lorem
         ipsum is what my brain feels like today" → loremIpsum). */
      if (asked && asked.asks === false) {
        return {
          message, routing, plan: { steps: [] }, results: [], ask: null, asked,
          mode: MODES.NO_SKILL,
          reply: { source: REPLY_SOURCES.NO_SKILL, segments: [], notes: [] },
          ms: Date.now() - t0, stages
        };
      }
      /* THE DECLINE SECOND LOOK. The planner said no skill; the category
         adapter said there is one. Ask a selection question over the router's
         top three, with "none" allowed. A named skill goes back to the
         planner as one card for its arguments — and if the message carries no
         data, the executor asks for it, which is the correct reply. */
      if (secondLook && categoryNamed) {
        const top = (routing.candidates || []).slice(0, 3).map(c => registry.compactCard(c.name)).filter(Boolean);
        const tLook = Date.now();
        const pick = top.length ? await secondLook({ message, cards: top }) : null;
        stages.secondLook = Date.now() - tLook;
        if (pick && pick.chosen) {
          const card = registry.compactCard(pick.chosen);
          const again = card ? await planner({ message, cards: [card], ctx, prev, carry, routerConfident: true }) : null;
          const replanned = again && Array.isArray(again.steps) && again.steps.length && again.steps.every(st => st.skill === pick.chosen);
          /* A planner shown one card tends to decline again — measured, that is
             the trust-router result. The selection already happened; if the
             planner will not write the arguments, §11's single-skill mode does
             what it always did: one step, empty input, the Extractor fills
             what the message holds and the executor asks for the rest. */
          const chosenPlan = replanned ? again : { steps: [{ id: 's1', skill: pick.chosen, input: {} }] };
          verified = { draft: null, chosen: pick.chosen, alternatives: top.map(c => c.name), secondLook: true, replanned: Boolean(replanned) };
          return finish({ message, routing, plan: chosenPlan, mode: replanned ? MODES.PLANNED : MODES.SINGLE_SKILL });
        }
      }
      /* THE ROUTER'S SECOND OPINION ON A DECLINE. Measured on the holdout:
         "multiply 7 by 9 by 3 together" put `product` first at 0.71 — over
         t_skill and clear of the runner-up, the same evidence single-skill
         mode acts on alone — and the planner still returned an empty plan.
         Sixteen of the bench's ninety misses have the wanted skill ranked
         first. So when the router is that sure and the planner declines,
         §11's fallback runs: one step, the router's pick, the Extractor fills
         the arguments and the executor asks for what it cannot find. Unlike
         handing the planner a single card (measured worse — it declined MORE
         when shown less), this touches only turns the planner already gave
         up on; the cost it can have is a no-skill message the router was
         wrongly sure about, which the bench counts.

         MEASURED, and that is why it is off: 212 → 213 answered, leaks 8 → 9.
         The declines it rescues are mostly messages with no data in them
         ("tidy this json"), and single-skill mode cannot fill an argument the
         message does not contain either — those become ASK_USER, which the
         bench scores as a miss and which is the correct outcome. The flag
         stays for the bench to re-measure when the extractor improves. */
      if (fallbackOnEmpty && routing.actionable && routing.actionable.length) {
        return finish({
          message, routing,
          plan: { steps: [{ id: 's1', skill: routing.actionable[0].name, input: {} }] },
          mode: MODES.SINGLE_SKILL
        });
      }
      /* SECOND LOOK. A question of fact that nothing offline can answer reaches
         here twice over: the router cannot rank a web skill it has no words in
         common with ("who is the govenor of virginia" — misspelt, and no skill
         says "virginia"), and the category adapter is no help either, because it
         was trained to answer "none" to general knowledge and is genuinely torn
         on these, splitting ~54/45 between reference and none and so never
         clearing its confidence bar.

         So rather than widen either gate — which would cost refusals everywhere
         — ask once more with ONLY the web skills on the table. It is the same
         planner and the same rules; what changes is that the web option is no
         longer buried under twenty offline near-misses. Measured on the 50
         no-skill messages, this does not move the leak rate: the planner
         declines a poem or a bad day just as firmly when the web is the only
         thing offered.

         Runs only when the web is actually on, so with it off every path below
         behaves exactly as it did before this existed. */
      /* Also under the "try the web when Patch can't" policy, where the plan it
         finds stops at the look-up card and still sends nothing without a yes. */
      const lookOnWeb = ctx.webEnabled || Boolean(ctx.webAvailable && ctx.webPolicy === 'fallback');
      if (lookOnWeb) stage('second-look');
      const second = lookOnWeb ? await webSecondLook({ message, ctx, prev, planner, registry }) : null;
      if (second) {
        plan = second;
        return finish({ message, routing, plan, mode: MODES.PLANNED });
      }
      return {
        message, routing, plan: plan || { steps: [] }, results: [], ask: null,
        mode: MODES.NO_SKILL,
        ...taughtBy(routing, registry),
        reply: { source: REPLY_SOURCES.NO_SKILL, segments: [], notes: [] },
        ms: Date.now() - t0, stages
      };
    }
  } else {
    /* §11's sanctioned fallback: top-1 skill, Extractor fills args, no
       multi-step. The plan is a single step with an empty input, and the
       executor's validate → Extractor → ASK_USER path does the rest. */
    plan = { steps: [{ id: 's1', skill: confident[0].name, input: {} }] };
    mode = MODES.SINGLE_SKILL;
  }

  return finish({ message, routing, plan, mode });

  async function finish ({ message: msg, routing: rt, plan: planned, mode, answered = null, consentAnswer = null }) {
    let plan = planned;
    /* A one-step plan whose skill has a twin the router also listed: the
       receipt can offer the twin, one tap. Never on a re-ask that chose one. */
    const twin = onlySkill ? null : twinListed(plan, rt);
    /* A Reply's plan, lined up with the answer it carries (carry.js). Never
       runs without a carried answer, so no other plan can change here. */
    let carryRepairs = [];
    if (carry && plan && mode !== MODES.HAND_WRITTEN) {
      const aligned = alignToCarry(plan, { carry, message: msg, registry });
      plan = aligned.plan;
      carryRepairs = aligned.repairs;
    }
    // ── JS: validate the plan before anything runs ────────────────────────
    const check = validatePlan(plan, registry, { prevResults });
    if (!check.ok) {
      return {
        message: msg, routing: rt, plan, results: [], ask: null, answered,
        mode, invalid: check.errors,
        reply: { source: REPLY_SOURCES.NO_SKILL, segments: [], notes: [] },
        ms: Date.now() - t0, stages
      };
    }

    // ── [3] Executor ─────────────────────────────────────────────────────
    /* An answer the user typed to an ASK_USER is as good as the message for
       the input audit — it is the user's own text. */
    const known = answered && typeof answered.value === 'string' ? [answered.value] : [];
    stage('running', { skills: (plan.steps || []).map(st => st.skill) });
    let run = await runPlan(plan, { registry, ctx, message: msg, prevResults, extractor, onNetworkConfirm, known, answered, consent: consentAnswer });

    /* SECOND OPINION FROM THE ROUTER. A planned single step that the skill
       itself rejected — "km measures length, and this converts speed" — while
       the router had an actionable pick that is a DIFFERENT skill is the one
       shape where the planner is demonstrably wrong and the router demonstrably
       confident: convertLength at 0.70 over convertSpeed at 0.27, and the 2B
       still chose convertSpeed. So ask the planner once more with only the
       router's skill on the table, which turns its job into copying the
       arguments out. This can only convert a failed turn into an answered one:
       it never runs on a decline, so it cannot add a no-skill leak, and if the
       re-plan is empty or fails too the original failure stands. */
    if (mode === MODES.PLANNED && planner && rt && rt.actionable && rt.actionable.length &&
        plan.steps.length === 1 && run.results.length === 1 && !run.results[0].ok &&
        run.results[0].error && run.results[0].error.code === ERROR_CODES.INVALID_INPUT &&
        rt.actionable[0].name !== plan.steps[0].skill) {
      const card = registry.compactCard(rt.actionable[0].name);
      const again = card ? await planner({ message: msg, cards: [card], ctx, prev, carry, routerConfident: true }) : null;
      if (again && Array.isArray(again.steps) && again.steps.length &&
          again.steps.every(st => st.skill === card.name) &&
          validatePlan(again, registry, { prevResults }).ok) {
        const rerun = await runPlan(again, { registry, ctx, message: msg, prevResults, extractor, onNetworkConfirm, known, answered, consent: consentAnswer });
        if (rerun.outcome !== OUTCOME.FAILED) {
          plan = again;
          run = rerun;
        }
      }
    }

    /* Stopped for a yes before a look-up. Nothing has left the machine; the
       turn carries what would be sent and to whom. */
    if (run.outcome === OUTCOME.CONSENT_WEB) {
      return {
        message: msg, routing: rt, plan, results: run.results, answered, resolvedPrev: prevRefsUsed(plan, run.results, prevResults), carryRepairs,
        ask: null, consent: run.consent, mode, reply: null, ms: Date.now() - t0, stages, ...(verified ? { verified } : {}), ...(asked ? { asked } : {}), ...(twin ? { twin } : {}), ...(onlySkill ? { chosen: onlySkill } : {})
      };
    }

    if (run.outcome === OUTCOME.ASK_USER) {
      return {
        message: msg, routing: rt, plan, results: run.results, answered, resolvedPrev: prevRefsUsed(plan, run.results, prevResults), carryRepairs,
        ask: run.ask, mode, reply: null, ms: Date.now() - t0, stages, ...(verified ? { verified } : {}), ...(asked ? { asked } : {}), ...(twin ? { twin } : {}), ...(onlySkill ? { chosen: onlySkill } : {})
      };
    }

    // ── [4] Assembler, or the template path that makes it unnecessary ────
    const reply = await replyFor(run.results, { registry, message: msg, ctx, assembler, focus, plan });
    /* A skill that ran and failed on its input ("1988" is not a date): the
       bubble shows the error, and under it the skill's own example with two
       of its neighbours, so the right shape is one tap away. */
    const failed = run.results.find(r => !r.ok && r.skill);
    const taught = failed ? taughtBy(rt, registry, { category: registry.skill(failed.skill)?.category, first: failed.skill }) : {};
    return {
      message: msg, routing: rt, plan, results: run.results, ask: null, answered, resolvedPrev: prevRefsUsed(plan, run.results, prevResults), carryRepairs,
      mode, reply, ms: Date.now() - t0, stages, ...taught, ...(verified ? { verified } : {}), ...(asked ? { asked } : {}), ...(twin ? { twin } : {}), ...(onlySkill ? { chosen: onlySkill } : {})
    };
  }
}

