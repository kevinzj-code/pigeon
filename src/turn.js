/** What is actually running behind each of §3's four passes, in this build. */
/* The second look, kept out of the main path so it reads as what it is: a
   retry with a narrower menu, not a special case in the pipeline. Returns a plan
   or null, and null is the normal answer. */
async function webSecondLook ({ message, ctx, prev, planner, registry }) {
  const cards = registry.routable()
    .filter(s => s.needsNetwork)
    .map(s => registry.compactCard(s.name))
    .filter(Boolean);
  if (!cards.length) return null;

  const plan = await planner({ message, cards, ctx, prev });
  if (!plan || !Array.isArray(plan.steps) || !plan.steps.length) return null;
  /* It was handed web skills only, but a model can still name something else.
     Anything that is not one of the offered skills is dropped rather than
     executed — the second look must not become a way to reach the other 301. */
  const offered = new Set(cards.map(c => c.name));
  return plan.steps.every(st => offered.has(st.skill)) ? plan : null;
}

/* ── an answer, as the field it is going into ────────────────────────────
 *
 * A person answering "which numbers should I add up?" types "5 10 15 20". The
 * field wants an array of numbers, and writing the string in raw made every
 * skill whose asked-for field is not plain text fail on resume — `sum` came
 * back "must be a number, got string" while the person watched.
 *
 * The extractor cannot help here: it is handed the ORIGINAL message, which by
 * definition lacked the value, and it only considers fields that are unset.
 * So the answer is converted here, from the field's own declared type, and
 * nothing else in the pipeline changes.
 *
 * Anything it cannot read confidently is left as typed, so the skill's own
 * validation still gets the last word and the person still sees a real error
 * rather than a guess.
 */
const NUMBER = /-?\d+(?:\.\d+)?/g;
const YES = /^(?:y|yes|yeah|yep|true|on|ok|okay)$/i;
const NO = /^(?:n|no|nope|false|off)$/i;

/* The "$prev" refs a plan actually read, each with the value it got, for steps
   that ran. This is what lets a reply say "using £97.18 from before" — and only
   about a figure that really was used, never one the model merely mentioned. */
export function prevRefsUsed (plan, results, prevResults) {
  const out = [];
  for (const step of (plan && plan.steps) || []) {
    const ran = (results || []).find(r => r && r.id === step.id && r.ok);
    if (!ran) continue;
    const text = JSON.stringify(step.input || {});
    for (const m of text.matchAll(/\$prev\.([A-Za-z][A-Za-z0-9_]*)((?:\.[A-Za-z0-9_]+)*)/g)) {
      const src = (prevResults || []).find(r => r && r.id === m[1] && r.ok);
      if (!src) continue;
      const path = m[2] ? m[2].slice(1).split('.') : [];
      const value = path.reduce((o, k) => (o === undefined || o === null ? undefined : o[k]), src.value);
      if (value === undefined) continue;
      out.push({ ref: m[0], step: step.id, skill: src.skill, field: path.join('.'), value });
    }
  }
  return out;
}

export function answerFor (registry, step, field, text) {
  const raw = String(text ?? '').trim();
  const spec = registry && registry.skill
    ? (((registry.skill(step.skill) || {}).inputSchema || {}).properties || {})[field]
    : null;
  if (!spec) return raw;

  const numbers = () => (raw.match(NUMBER) || []).map(Number).filter(Number.isFinite);

  if (spec.type === 'array') {
    const items = (spec.items && spec.items.type) || 'string';
    if (items === 'number' || items === 'integer') {
      const got = numbers();
      return got.length ? got : raw;
    }
    /* A list of strings: commas and newlines are how people separate them.
       A single value with neither is a one-item list, not a sentence split. */
    const parts = raw.split(/[,\n]+/).map(p => p.trim()).filter(Boolean);
    return parts.length ? parts : raw;
  }
  if (spec.type === 'number' || spec.type === 'integer') {
    const got = numbers();
    return got.length === 1 ? got[0] : raw;
  }
  if (spec.type === 'boolean') {
    if (YES.test(raw)) return true;
    if (NO.test(raw)) return false;
    return raw;
  }
  /* An answer to "Which mode: nth or sequence?" may be a sentence ("the whole
     sequence"). Exactly one of the choices named in it is the answer. */
  if (Array.isArray(spec.enum) && !spec.enum.includes(raw)) {
    const named = spec.enum.filter(e => typeof e === 'string' && new RegExp(`(^|[^a-z0-9])${e.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}($|[^a-z0-9])`, 'i').test(raw));
    if (named.length === 1) return named[0];
  }
  return raw;
}

export function stackReport ({ router, planner, extractor, assembler, focus = null, model = null, ocr = null, engine = null, laneB = null }) {
  return [
    { pass: 'router', state: 'on', detail: router ? router.name : 'none' },
    /* The engine and its weights: Pigeon's own, or none (a browser). `engine` is { status, models } from engine.js,
       null where there is no bridge. */
    ...engineRows(engine && engine.status, engine && engine.models),
    {
      pass: 'planner',
      /* "sub" — a stand-in — covers BOTH the no-model case and a prompted
         model, because §9 Phase 5's adapter is what "on" would mean and no
         adapter exists. A prompted 2B answering 71% of the holdout is a real
         planner and a real result; it is not the trained one. */
      state: 'sub',
      detail: planner
        ? `${model || 'model'} · prompted, no adapter`
        : 'single-skill mode · no model'
    },
    {
      pass: 'extractor',
      state: extractor ? 'sub' : 'off',
      detail: extractor ? (extractor.backend || 'javascript') : 'none'
    },
    {
      pass: 'assembler',
      /* "sub" when the focus pass is running: it fills §8's seam, but by
         SELECTING one of the source's own sentences rather than writing prose.
         Claiming "on" would over-state it — no model writes a reply in THIS
         lane, whatever the chat lane may be doing — and "off" would under-state
         a pass that is doing the assembler's job on every web answer. */
      state: assembler ? 'on' : (focus ? 'sub' : 'off'),
      detail: assembler
        ? 'chat model'
        : (focus ? 'answer focus · model picks the sentence, the plan picks the step' : 'not installed · replies from templates')
    },
    {
      /* The second lane. "on" is reserved for the lane as the spec describes
         it — a model writing in a trained voice — because a persona is the
         part that had to be built and the part that is not here yet. Chatting
         with the base model is real and useful and is still a stand-in for
         that, so it says so rather than claiming the finished thing. */
      pass: 'lane b',
      state: !laneB || !laneB.ready ? 'off' : (laneB.personas > 0 ? 'on' : 'sub'),
      detail: !laneB
        ? 'the app only · no chat model in a browser'
        : !laneB.ready
          ? 'asleep · wake the models to chat with a Pigeon'
          : laneB.personas > 0
            ? `generated · ${laneB.personas} persona${laneB.personas === 1 ? '' : 's'} loaded`
            : 'generated · base weights, no persona trained yet'
    },
    {
      pass: 'vision',
      /* "sub" at best: a classical OCR engine standing in for a vision model,
         with the planner tidying its reading when one is up. Experimental, and
         the row says which half of it is actually running. */
      state: ocr ? 'sub' : 'off',
      detail: ocr
        ? `${ocr.engine || 'the text reader'} · ${model ? `tidied by ${model}` : 'raw, no model to tidy'}`
        : 'no text reader · images cannot be read'
    }
  ];
}

/* ── a decline that teaches, and one tap to the twin ──────────────────────
 *
 * Both read what the turn already knows; neither asks a model. */

/** When the router named a category with confidence and the planner still
 *  declined, three of that category's skills, the ones nearest the message
 *  first (the lexical router's scores order them; the rest by name), for
 *  the bubble to offer as examples: `{ taught: { category, skills } }`, or
 *  nothing. */
export function taughtBy (routing, registry, { category: given = null, first = null } = {}) {
  /* A category given by the caller is the failed skill's own, and is sure;
     the router's needs its confidence. */
  const category = given || (routing && routing.category);
  if (!category || category === 'unavailable' || category === 'none') return {};
  if (!given && typeof routing.confidence === 'number' && routing.confidence < (routing.minConfidence ?? 0.8)) return {};
  const score = new Map(((routing && routing.candidates) || []).map(c => [c.name, c.score || 0]));
  const members = registry.routable().filter(e => e.category === category && e.examples && e.examples[0]);
  if (!members.length) return {};
  const rank = (e) => (e.name === first ? Infinity : (score.get(e.name) || 0));
  const skills = members
    .sort((a, b) => rank(b) - rank(a) || a.name.localeCompare(b.name))
    .slice(0, 3)
    .map(e => e.name);
  return { taught: { category, skills } };
}

const TWINS = twinIndex();

/** The twin of a one-step plan's skill that the router listed for this
 *  message, or null. Only a skill on the router's own list can be offered:
 *  the planner saw it and chose the other, which is the confusion worth a
 *  tap. */
export function twinListed (plan, routing) {
  const steps = plan && Array.isArray(plan.steps) ? plan.steps : [];
  if (steps.length !== 1 || !steps[0] || !steps[0].skill) return null;
  const chosen = steps[0].skill;
  const listed = new Set((routing && routing.forPlanner || []).map(c => c.name));
  const twin = (TWINS.get(chosen) || []).find(t => listed.has(t));
  return twin || null;
}
