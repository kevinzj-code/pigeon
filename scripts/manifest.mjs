#!/usr/bin/env node
/* manifest.mjs — regenerate skills/index.js from the folder.
 *
 * The manifest is explicit (the browser cannot list a directory) but it does
 * not have to be hand-maintained. This reads every skill file, groups by the
 * `category` each one declares, and writes the imports and the export array.
 * `npm test` still checks the result against the folder, so this script is a
 * convenience, not a source of truth — if it and the test disagree, the test
 * is right. */

import { readdir, writeFile } from 'node:fs/promises';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'skills');

const files = (await readdir(DIR))
  .filter(f => f.endsWith('.js') && f !== 'index.js' && !f.startsWith('_'))
  .map(f => f.replace(/\.js$/, ''))
  .sort();

/* The module is imported rather than pattern-matched. Reading `category:` out of
   the source text worked until the convert* skills started being built by
   makeConverter, whose source never contains the literal — all eight quietly
   fell into a synthetic "other" group. The value the registry actually uses is
   the one on the module, so that is the one to read. */
const entries = [];
for (const f of files) {
  const mod = (await import(pathToFileURL(join(DIR, `${f}.js`)).href)).default;
  if (!mod?.name) throw new Error(`${f}.js has no name`);
  entries.push({ file: f, name: mod.name, category: mod.category ?? 'other' });
}

const cats = [...new Set(entries.map(e => e.category))].sort();
const out = [`/* index.js — the registry manifest. GENERATED by scripts/manifest.mjs.
 *
 * Explicit rather than directory-scanned, because the browser cannot list a
 * directory and a build step that generates this at load time is a build step
 * Pigeon does not otherwise need. \`npm test\` checks this list against the
 * folder, so a skill added and not listed fails loudly instead of silently not
 * existing.
 *
 * Names follow \`pigeon-skill-index-v0.md\` exactly — camelCase, verbNoun.
 * Grouped by the category each skill declares. Re-run \`npm run manifest\`
 * after adding one.
 */
`];

for (const c of cats) {
  const group = entries.filter(e => e.category === c);
  out.push(`// ${c} (${group.length})`);
  for (const e of group) out.push(`import ${e.name} from './${e.file}.js';`);
  out.push('');
}
out.push('// §2.4/§5 — registered, unbuilt, never routable');
out.push("import extendedStubs from './_extended-stubs.js';");
out.push("import blockedSkills from './_blocked.js';");
out.push('');
out.push('export default [');
for (const c of cats) {
  const group = entries.filter(e => e.category === c);
  out.push(`  // ${c}`);
  let line = '  ';
  for (const e of group) {
    if (line.length + e.name.length + 2 > 96) { out.push(line.trimEnd()); line = '  '; }
    line += `${e.name}, `;
  }
  out.push(line.trimEnd());
}
out.push('  ...extendedStubs,');
out.push('  ...blockedSkills');
out.push('];');

await writeFile(join(DIR, 'index.js'), `${out.join('\n')}\n`);
console.log(`  skills/index.js ← ${entries.length} skills across ${cats.length} categories`);
